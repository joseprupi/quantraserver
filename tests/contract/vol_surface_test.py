"""Black vol surface from option quotes (/calibrate-vol-surface).

The synthetic SVI sheet under examples/data/vol_surface/ is generated by
tests/tools/make_synthetic_quote_sheet.py from a stated SSVI surface
(rho = -0.7, ATM vols per expiry), exact mids with a 1 % bid/ask. End to end
through the JSON gateway these tests pin:

  * the committed examples equal the generator's output;
  * SviPerExpiry recovers the generating slices on the grid within 0.1 vol
    points everywhere (wings included), AndreasenHuge within 0.25 vol points
    on the informative quotes of the quoted strike range;
  * both methods equal the Python reference (calibrate_vol_surface_ql, same
    QuantLib classes) field for field;
  * a flat 20 % sheet gives 20 % everywhere;
  * the two-step flow: the implied-forwards response pasted as `forwards`
    gives the same surface as the internal fit;
  * acceptance: the returned vol_surface_spec pasted into a
    price-equity-option request, next to the implied dividend curve,
    reprices the used quotes inside their bid/ask;
  * the returned grid is read with CubicStrikeLinearTime: it reproduces its
    own nodes exactly and sits within 0.05 vol points of the generating SVI
    between them (a bilinear reading of the same grid is 0.4 vol points off
    on the short wing), sampled through /sample-vol-surfaces;
  * SviPerExpiry also returns `vol_surface_spec_svi` (the fitted slices as
    an SviVolSpec payload): a European option priced on it equals the Black
    price at the slice's vol (the same market under a Constant vol) to
    1e-10; AndreasenHuge returns the note instead;
  * the pasted surface (grid or SVI payload) prices a structured note with
    steps_per_year;
  * the 400s, the SviVolSpec payload's included.
"""

