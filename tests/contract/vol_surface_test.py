"""Black vol surface from option quotes (/calibrate-vol-surface).

The synthetic SVI sheet under examples/data/vol_surface/ is generated by
tests/tools/make_synthetic_quote_sheet.py from a stated SSVI surface
(rho = -0.7, ATM vols per expiry), exact mids with a 1 % bid/ask. End to end
through the JSON gateway these tests pin:

  * the committed examples equal the generator's output;
  * SviPerExpiry recovers the generating slices on the grid within 0.1 vol
    points everywhere (wings included), AndreasenHuge within 0.25 vol points
    on the informative quotes of the quoted strike range;
  * both methods equal the Python reference (calibrate_vol_surface_ql, same
    QuantLib classes) field for field;
  * a flat 20 % sheet gives 20 % everywhere;
  * the two-step flow: the implied-forwards response pasted as `forwards`
    gives the same surface as the internal fit;
  * acceptance: the returned vol_surface_spec pasted into a
    price-equity-option request, next to the implied dividend curve,
    reprices the used quotes inside their bid/ask;
  * the pasted surface prices a structured note with steps_per_year;
  * the 400s.
"""

import copy
import math
import sys
from pathlib import Path

import pytest

from ql_reference import calibrate_vol_surface_ql, load_json

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tests" / "tools"))

import make_synthetic_quote_sheet as gen  # noqa: E402

AH_EXAMPLE = "vol_surface/synthetic_svi_sheet_2026-09-30_andreasen_huge.json"
SVI_EXAMPLE = "vol_surface/synthetic_svi_sheet_2026-09-30_svi.json"
NOTE_EXAMPLE = "structured_note/scotia_autocallable_trigger_ndx_rty_us06419jme72_with_synthetic_surface.json"


def _post(client, request, product="calibrate_vol_surface"):
    return client.session.post(
        f"{client.base_url}/{client.ENDPOINTS[product]}", json=request)


def _ok(client, request, product="calibrate_vol_surface"):
    r = _post(client, request, product)
    assert r.status_code == 200, r.text[:600]
    return r.json()


def _grid(out):
    """{(expiry, strike): vol} from the returned spec."""
    spec = out["vol_surface_spec"]["payload"]
    strikes = spec["strikes"]
    expiries = out["grid_expiries"]
    values = spec["surface_vols"]["values"]
    assert spec["surface_vols"]["n_rows"] == len(expiries)
    assert spec["surface_vols"]["n_cols"] == len(strikes)
    return {(e, k): values[i * len(strikes) + j]
            for i, e in enumerate(expiries) for j, k in enumerate(strikes)}


def _truth_vol(preset, expiry, strike):
    f = gen.truth(preset)[expiry]["forward"]
    return gen.smile_vol(preset, math.log(strike / f), expiry)


def _informative(request, expiry):
    """Quotes of the expiry whose out-of-the-money mid is at least 1e-5 of
    the spot (the engine's quote-resolution rule)."""
    spot = request["pricing"]["quotes"][0]["value"]
    f = gen.truth(gen.SYNTHETIC_SVI_NDX_LIKE)[expiry]["forward"]
    n = 0
    for q in request["sheet"]["quotes"]:
        if q["expiry"] != expiry:
            continue
        mid = 0.5 * (q["call_bid"] + q["call_ask"]) if q["strike"] >= f else \
            0.5 * (q["put_bid"] + q["put_ask"])
        n += mid >= 1e-5 * spot
    return n


def _dig(obj, path):
    for part in path.split("."):
        obj = obj[int(part)] if isinstance(obj, list) else obj[part]
    return obj


def test_examples_equal_generator(data_dir):
    assert load_json(data_dir / AH_EXAMPLE) == \
        gen.build_vol_surface_request(gen.SYNTHETIC_SVI_NDX_LIKE, "AndreasenHuge")
    assert load_json(data_dir / SVI_EXAMPLE) == \
        gen.build_vol_surface_request(gen.SYNTHETIC_SVI_NDX_LIKE, "SviPerExpiry")


def test_response_shape_and_spec(client, data_dir):
    request = load_json(data_dir / SVI_EXAMPLE)
    out = _ok(client, request)
    assert out["sheet_id"] == request["sheet"]["id"]
    assert out["underlying_id"] == "NDX_SYN"
    assert out["spot"] == 24000.0
    assert out["method"] == "SviPerExpiry"
    assert out["forwards_source"] == "fitted"
    assert out["filter"] == request["filter"]
    assert len(out["forwards"]) == 8 and len(out["expiries"]) == 8
    assert out["strikes_as_moneyness"] == pytest.approx([0.5 + 0.025 * i for i in range(41)])
    assert out["grid_strikes"] == pytest.approx([24000.0 * m for m in out["strikes_as_moneyness"]])
    assert out["grid_expiries"] == [e for e, _q in gen.SYNTHETIC_SVI_NDX_LIKE["expiries"]]
    spec = out["vol_surface_spec"]
    assert spec["id"] == "NDX_SYN_VOL" and spec["payload_type"] == "BlackVolSpec"
    base = spec["payload"]["base"]
    assert base == {"reference_date": "2026-09-30", "calendar": "NullCalendar",
                    "business_day_convention": "Unadjusted", "day_counter": "Actual365Fixed",
                    "shape": "SmileCube3D"}
    assert spec["payload"]["allow_extrapolation"] is True
    assert spec["payload"]["expiries"] == [{"n": 16, "unit": "Days"}, {"n": 51, "unit": "Days"},
                                           {"n": 79, "unit": "Days"}, {"n": 107, "unit": "Days"},
                                           {"n": 170, "unit": "Days"}, {"n": 261, "unit": "Days"},
                                           {"n": 352, "unit": "Days"}, {"n": 443, "unit": "Days"}]
    used = 0
    for e in out["expiries"]:
        assert e["usable"] and e["quotes_used"] == _informative(request, e["expiry"])
        assert e["quotes_used"] + e["quotes_dropped"] == 25
        for d in e["dropped"]:
            assert "quote resolution" in d["reason"]
        assert e["butterfly_action"] == "none" and e["calendar_action"] == "none"
        assert e["rmse_vol"] < 1e-8
        assert set(e["svi"]) == {"a", "b", "sigma", "rho", "m"}
        used += e["quotes_used"]
    assert used > 150
    rp = out["vanilla_repricing"]
    assert rp["count"] == used and rp["inside_bid_ask"] == used
    assert len(rp["quotes"]) == used
    assert rp["max_abs_vol_error"] < 1e-6


def test_svi_recovers_the_generating_surface(client, data_dir):
    out = _ok(client, load_json(data_dir / SVI_EXAMPLE))
    preset = gen.SYNTHETIC_SVI_NDX_LIKE
    worst = 0.0
    for (expiry, strike), vol in _grid(out).items():
        worst = max(worst, abs(vol - _truth_vol(preset, expiry, strike)))
    assert worst < 1e-3, worst  # 0.1 vol point, wings included
    for e in out["expiries"]:
        truth = gen.svi_params(preset, e["expiry"])
        assert abs(e["svi"]["rho"] - truth["rho"]) < 1e-6
        assert abs(e["svi"]["b"] - truth["b"]) < 1e-6


def test_andreasen_huge_reproduces_the_surface_on_informative_quotes(client, data_dir):
    out = _ok(client, load_json(data_dir / AH_EXAMPLE))
    assert out["method"] == "AndreasenHuge"
    assert out["andreasen_huge_error"]["max_vol"] < 2.5e-3
    preset = gen.SYNTHETIC_SVI_NDX_LIKE
    truth = gen.truth(preset)
    worst, compared = 0.0, 0
    for (expiry, strike), vol in _grid(out).items():
        if not 0.70 * 24000.0 - 1e-6 <= strike <= 1.30 * 24000.0 + 1e-6:
            continue
        tv = _truth_vol(preset, expiry, strike)
        f, df, t = truth[expiry]["forward"], truth[expiry]["discount_factor"], truth[expiry]["time"]
        call, put = gen.black_call_put(f, strike, tv, t, df)
        if (call if strike >= f else put) < 1e-4 * 24000.0:
            continue  # not determined by a 1 % bid/ask on a price below 2.4 points
        worst = max(worst, abs(vol - tv))
        compared += 1
    assert compared > 60
    assert worst < 2.5e-3, worst  # 0.25 vol point
    for e in out["expiries"]:
        assert "svi" not in e and e["usable"]
        assert e["calendar_action"].startswith(("none", "reported only"))
    rp = out["vanilla_repricing"]
    outside = [(q["expiry"], q["strike"], q["mid"]) for q in rp["quotes"] if not q["inside_bid_ask"]]
    assert rp["count"] > 150 and rp["inside_bid_ask"] * 100 >= rp["count"] * 95, outside
    # The quotes outside are the short-dated wing ones priced below 1e-4 of the spot.
    assert all(mid < 1e-4 * 24000.0 for _e, _k, mid in outside), outside


@pytest.mark.parametrize("example,tol", [(AH_EXAMPLE, 1e-6), (SVI_EXAMPLE, 1e-6)])
def test_api_equals_python_reference(client, data_dir, example, tol):
    request = load_json(data_dir / example)
    out = _ok(client, request)
    expected = calibrate_vol_surface_ql(request)
    assert len(expected) > 250
    worst, where = 0.0, None
    for path, ref in expected.items():
        api = _dig(out, path)
        if isinstance(ref, list):
            assert len(api) == len(ref), path
            pairs = zip(api, ref)
        else:
            pairs = [(api, ref)]
        for a, b in pairs:
            if abs(a - b) > worst:
                worst, where = abs(a - b), (path, a, b)
    assert worst < tol, where


@pytest.mark.parametrize("method", ["AndreasenHuge", "SviPerExpiry"])
def test_flat_twenty_percent(client, method):
    out = _ok(client, gen.build_vol_surface_request(gen.SYNTHETIC_FLAT_20, method))
    grid = _grid(out)
    assert len(grid) == 8 * 41
    quoted = [abs(v - 0.20) for (_e, k), v in grid.items() if 0.7 * 24000.0 - 1e-6 <= k <= 1.3 * 24000.0 + 1e-6]
    assert max(quoted) < 1e-3
    assert max(abs(v - 0.20) for v in grid.values()) < (1e-3 if method == "SviPerExpiry" else 1e-2)
    assert out["vanilla_repricing"]["inside_bid_ask"] == out["vanilla_repricing"]["count"]
    for e in out["expiries"]:
        assert e["calendar_violations"] == 0 and not e["butterfly_violation"]


def test_pasted_forwards_give_the_same_surface(client, data_dir):
    request = load_json(data_dir / SVI_EXAMPLE)
    fitted = _ok(client, request)
    fwd_request = gen.build_request(gen.SYNTHETIC_SVI_NDX_LIKE)
    forwards = _ok(client, fwd_request, "calibrate_implied_forwards")
    pasted = dict(request)
    pasted["forwards"] = forwards["expiries"]
    out = _ok(client, pasted)
    assert out["forwards_source"] == "request"
    assert out["forwards"] == fitted["forwards"]
    a, b = _grid(out), _grid(fitted)
    # The forwards pass through the JSON print (15 significant digits).
    assert max(abs(a[k] - b[k]) for k in a) < 1e-9
    # Only usable entries count: dropping one expiry's forward drops that slice.
    pasted["forwards"] = [f for f in forwards["expiries"] if f["expiry"] != "2027-03-19"]
    out = _ok(client, pasted)
    e = next(x for x in out["expiries"] if x["expiry"] == "2027-03-19")
    assert not e["usable"] and "no forward" in e["dropped_reason"]
    assert len(out["grid_expiries"]) == 7


def test_custom_grid(client, data_dir):
    request = load_json(data_dir / AH_EXAMPLE)
    request["output_grid"] = {"strikes_as_moneyness": [0.8, 0.9, 1.0, 1.1, 1.2],
                              "expiries": [{"n": 1, "unit": "Months"}, {"n": 170, "unit": "Days"}]}
    out = _ok(client, request)
    assert out["grid_expiries"] == ["2026-10-30", "2027-03-19"]
    assert out["vol_surface_spec"]["payload"]["expiries"] == [{"n": 30, "unit": "Days"},
                                                              {"n": 170, "unit": "Days"}]
    assert out["grid_strikes"] == pytest.approx([19200.0, 21600.0, 24000.0, 26400.0, 28800.0])
    assert out["expiries"][0]["grid_points_filled"] == 0
    assert len(out["vol_surface_spec"]["payload"]["surface_vols"]["values"]) == 10
    # The 1M date is not a sheet expiry: fine for Andreasen-Huge, a 400 for SVI.
    request["method"] = "SviPerExpiry"
    r = _post(client, request)
    assert r.status_code == 400 and "not a fitted sheet expiry" in r.text


@pytest.mark.parametrize("example", [SVI_EXAMPLE, AH_EXAMPLE])
def test_pasted_surface_reprices_the_quotes_through_price_equity_option(client, data_dir, example):
    """Acceptance: the returned spec, next to the implied dividend curve, prices
    the used quotes inside their bid/ask with the vanilla pricer."""
    request = load_json(data_dir / example)
    out = _ok(client, request)
    forwards = _ok(client, gen.build_request(gen.SYNTHETIC_SVI_NDX_LIKE),
                   "calibrate_implied_forwards")
    pricing = copy.deepcopy(request["pricing"])
    pricing["rates"]["curves"].append(forwards["dividend_curve_spec"])
    pricing["equity"]["equity_underlyings"][0]["dividend_yield_curve_id"] = \
        forwards["dividend_curve_spec"]["id"]
    pricing["volatility"] = {
        "vol_surfaces": [out["vol_surface_spec"]],
        "models": [{"id": "bs", "payload_type": "EquityVanillaModelSpec",
                    "payload": {"model_type": "BlackScholesAnalytic"}}],
    }
    # Every used quote of three expiries, the out-of-the-money side.
    sample = [q for q in out["vanilla_repricing"]["quotes"]
              if q["expiry"] in ("2026-11-20", "2027-03-19", "2027-12-17")]
    assert len(sample) >= 60
    options = []
    for n, q in enumerate(sample):
        options.append({
            "option": {
                "trade_id": f"q{n}", "underlying_id": "NDX_SYN", "quantity": 1.0,
                "settlement": "Physical",
                "payoff_type": "EquityPlainVanillaPayoff",
                "payoff": {"option_type": q.get("option_type", "Call"), "strike": q["strike"]},
                "exercise_type": "EquityEuropeanExercise",
                "exercise": {"expiry_date": q["expiry"]},
            },
            "discounting_curve": request["discounting_curve"],
            "volatility": out["vol_surface_spec"]["id"], "model": "bs",
        })
    priced = client.price("equity_option", {"pricing": pricing, "options": options})
    inside = 0
    worst_rel = 0.0
    for q, o in zip(sample, priced["options"]):
        npv = o["npv"]
        # The pricer and the endpoint's own repricing agree (same surface, same
        # forward: the dividend curve reproduces it; same DF: zero funding).
        assert abs(npv - q["model_price"]) <= 1e-6 * max(1.0, q["mid"]), (q, npv)
        if q["bid"] <= npv <= q["ask"]:
            inside += 1
        worst_rel = max(worst_rel, abs(npv - q["mid"]) / q["mid"])
    if example == SVI_EXAMPLE:
        assert inside == len(sample)
    else:
        assert inside >= len(sample) - 3, (inside, worst_rel)


def test_pasted_surface_prices_a_structured_note(client, data_dir):
    """The committed Scotia request with synthetic surfaces for NDX and RTY
    prices under Dupire local vol (steps_per_year present)."""
    request = load_json(data_dir / NOTE_EXAMPLE)
    for vs in request["pricing"]["volatility"]["vol_surfaces"]:
        assert vs["payload"]["base"]["shape"] == "SmileCube3D"
    assert request["notes"][0]["monte_carlo"]["steps_per_year"] == 252
    out = client.price("structured_note", request)
    note = out["notes"][0]
    assert math.isfinite(note["npv"]) and 500.0 < note["npv"] < 1200.0
    assert note["model"]["underlyings"][0]["vol_shape"] == "SmileCube3D"


def test_rejected_requests(client, data_dir):
    base = load_json(data_dir / AH_EXAMPLE)

    r = _post(client, {**base, "sheet": {**base["sheet"], "option_style": "American"}})
    assert r.status_code == 400 and "option_style" in r.text

    r = _post(client, {**base, "output_grid": {"strikes_as_moneyness": [1.0, 0.9]}})
    assert r.status_code == 400 and "strictly increasing" in r.text

    r = _post(client, {**base, "output_grid": {"expiries": [{"n": 5, "unit": "Years"}]}})
    assert r.status_code == 400 and "after the last fitted sheet expiry" in r.text

    r = _post(client, {**base, "filter": {"moneyness_window": 0.0}})
    assert r.status_code == 400 and "moneyness_window" in r.text

    r = _post(client, {**base, "forwards": [{"expiry": "2026-10-16", "usable": True,
                                             "forward": -1.0, "implied_discount_factor": 0.99}]})
    assert r.status_code == 400 and "forward must be finite and > 0" in r.text

    r = _post(client, {**base, "forwards": []})
    assert r.status_code == 400 and "no usable expiry" in r.text

    r = _post(client, {**base, "discounting_curve": "EUR_OIS"})
    assert r.status_code == 404

    no_id = {k: v for k, v in base.items() if k != "vol_surface_id"}
    r = _post(client, no_id)
    assert r.status_code == 400 and "vol_surface_id" in r.text
