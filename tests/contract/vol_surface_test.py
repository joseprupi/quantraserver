def _post(client, request, product="calibrate_vol_surface"):
    return client.session.post(
        f"{client.base_url}/{client.ENDPOINTS[product]}", json=request)


def _ok(client, request, product="calibrate_vol_surface"):
    r = _post(client, request, product)
    assert r.status_code == 200, r.text[:600]
    return r.json()


def _grid(out):
    """{(expiry, strike): vol} from the returned spec."""
    spec = out["vol_surface_spec"]["payload"]
    strikes = spec["strikes"]
    expiries = out["grid_expiries"]
    values = spec["surface_vols"]["values"]
    assert spec["surface_vols"]["n_rows"] == len(expiries)
    assert spec["surface_vols"]["n_cols"] == len(strikes)
    return {(e, k): values[i * len(strikes) + j]
            for i, e in enumerate(expiries) for j, k in enumerate(strikes)}


def _truth_vol(preset, expiry, strike):
    f = gen.truth(preset)[expiry]["forward"]
    return gen.smile_vol(preset, math.log(strike / f), expiry)


def _informative(request, expiry):
    """Quotes of the expiry whose out-of-the-money mid is at least 1e-5 of
    the spot (the engine's quote-resolution rule)."""
    spot = request["pricing"]["quotes"][0]["value"]
    f = gen.truth(gen.SYNTHETIC_SVI_NDX_LIKE)[expiry]["forward"]
    n = 0
    for q in request["sheet"]["quotes"]:
        if q["expiry"] != expiry:
            continue
        mid = 0.5 * (q["call_bid"] + q["call_ask"]) if q["strike"] >= f else \
            0.5 * (q["put_bid"] + q["put_ask"])
        n += mid >= 1e-5 * spot
    return n


def _dig(obj, path):
    for part in path.split("."):
        obj = obj[int(part)] if isinstance(obj, list) else obj[part]
    return obj


