def test_no_surviving_expiry_is_400_listing_the_reasons(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    request["filter"]["max_relative_spread"] = 0.001  # every line is 1 % wide
    r = _post(client, request)
    assert r.status_code == 400, r.text[:300]
    assert "No expiry" in r.text and "2026-10-16" in r.text and "2027-12-17" in r.text
    assert "min_quotes_per_expiry" in r.text


