"""Implied forwards and dividends from option quotes (/calibrate-implied-forwards).

The synthetic NDX-like sheet under examples/data/implied_forwards/ is
generated by tests/tools/make_synthetic_quote_sheet.py from a stated spot,
zero curve, dividend yield per expiry and Black smile, with exact mids and a
1 % bid/ask. These tests pin, end to end through the JSON gateway:

  * the committed example equals the generator's output (no hand edits);
  * the engine recovers the generating forward, discount factor and
    dividend yield at every expiry to 1e-10 (relative on prices, absolute on
    rates) and reports a zero funding spread against the same curve;
  * the response equals the independent Python reference
    (calibrate_implied_forwards_ql) field for field to 1e-9 relative;
  * the returned dividend_curve_spec is ready to use: pasted into a
    price-equity-option request next to the discounting curve, a call/put
    pair reproduces the forward through put-call parity;
  * the dropped-quote reporting: strikes outside the moneyness window, a
    crossed line, an expiry with three pairs, and open-interest filtering;
  * the 400s: American style, no surviving expiry, bad filter values.
"""

import copy
import math
import sys
from pathlib import Path

import pytest

from ql_reference import calibrate_implied_forwards_ql, load_json

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tests" / "tools"))

import make_synthetic_quote_sheet as gen  # noqa: E402

EXAMPLE = "implied_forwards/synthetic_ndx_like_2026-09-30.json"


def _post(client, request, product="calibrate_implied_forwards"):
    return client.session.post(
        f"{client.base_url}/{client.ENDPOINTS[product]}", json=request)


def _ok(client, request):
    r = _post(client, request)
    assert r.status_code == 200, r.text[:400]
    return r.json()


def _close(a, b, rel=1e-9):
    return abs(a - b) <= rel * max(1.0, abs(b))


def test_example_equals_generator(data_dir):
    assert load_json(data_dir / EXAMPLE) == gen.build_request(gen.SYNTHETIC_NDX_LIKE)


def test_recovers_the_generating_forwards_and_yields(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    out = _ok(client, request)
    truth = gen.truth(gen.SYNTHETIC_NDX_LIKE)
    assert out["sheet_id"] == request["sheet"]["id"]
    assert out["underlying_id"] == "NDX_SYN"
    assert out["spot"] == gen.SYNTHETIC_NDX_LIKE["spot"]
    assert [e["expiry"] for e in out["expiries"]] == list(truth)
    assert all(e["usable"] for e in out["expiries"])
    for e in out["expiries"]:
        tv = truth[e["expiry"]]
        assert abs(e["forward"] / tv["forward"] - 1.0) < 1e-10, e["expiry"]
        assert abs(e["implied_discount_factor"] / tv["discount_factor"] - 1.0) < 1e-10
        assert abs(e["curve_discount_factor"] / tv["discount_factor"] - 1.0) < 1e-12
        assert abs(e["implied_dividend_yield"] - tv["dividend_yield"]) < 1e-10
        assert abs(e["implied_funding_bp"]) < 1e-6
        assert abs(e["time"] - tv["time"]) < 1e-12
        assert e["fit_residual_rmse"] < 1e-8 and e["max_abs_residual"] < 1e-8
        # 25 strikes on the sheet, the ones outside +/-25 % of F are reported.
        assert e["quotes_used"] + e["quotes_dropped"] == 25
        assert e["quotes_used"] >= 20
        for d in e["dropped"]:
            # Far strikes leave the window; the furthest short-dated calls
            # have Black prices that underflow to 0 and fail the ask > 0 rule.
            assert d["reason"].startswith("outside moneyness window") or \
                d["reason"] == "negative bid or non-positive ask", d
            assert d["strike"] < tv["forward"] * 0.75 or d["strike"] > tv["forward"] * 1.25
    # Plain forward table and dividend curve follow the fitted expiries.
    assert [f["expiry"] for f in out["forwards"]] == list(truth)
    for f in out["forwards"]:
        assert abs(f["forward"] / truth[f["expiry"]]["forward"] - 1.0) < 1e-10
    spec = out["dividend_curve_spec"]
    assert spec["id"] == request["dividend_curve_id"]
    assert spec["bootstrap_trait"] == "InterpolatedZero"
    assert spec["day_counter"] == "Actual365Fixed"
    assert spec["interpolator"] == "Linear"
    assert spec["reference_date"] == request["pricing"]["as_of_date"]
    pts = spec["points"]
    assert [p["point"]["date"] for p in pts] == [request["pricing"]["as_of_date"]] + list(truth)
    assert all(p["point_type"] == "ZeroRatePoint" for p in pts)
    assert all(p["point"]["compounding"] == "Continuous" for p in pts)
    assert abs(pts[0]["point"]["zero_rate"] - truth["2026-10-16"]["dividend_yield"]) < 1e-10
    for p in pts[1:]:
        assert abs(p["point"]["zero_rate"] - truth[p["point"]["date"]]["dividend_yield"]) < 1e-10
    # The filter is echoed (request values).
    assert out["filter"] == request["filter"]


def test_matches_the_python_reference(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    out = _ok(client, request)
    expected = calibrate_implied_forwards_ql(request)
    assert len(expected) == 8 * 9 + 8 * 3 + 9
    for path, value in expected.items():
        got = out
        for part in path.split("."):
            got = got[int(part)] if isinstance(got, list) else got[part]
        assert _close(got, value), (path, got, value)


def test_dividend_curve_spec_reproduces_the_forward_in_pricing(client, data_dir):
    """Paste the returned curve into an equity-option request: the parity of
    a call/put pair priced on (discounting curve, implied dividend curve)
    gives back the fitted forward, for any vol."""
    request = load_json(data_dir / EXAMPLE)
    out = _ok(client, request)
    expiry = "2027-06-18"
    report = next(e for e in out["expiries"] if e["expiry"] == expiry)
    pricing = copy.deepcopy(request["pricing"])
    pricing["rates"]["curves"].append(out["dividend_curve_spec"])
    pricing["equity"]["equity_underlyings"][0]["dividend_yield_curve_id"] = \
        out["dividend_curve_spec"]["id"]
    pricing["volatility"] = {
        "vol_surfaces": [{
            "id": "flat_vol",
            "payload_type": "BlackVolSpec",
            "payload": {"base": {
                "reference_date": pricing["as_of_date"], "calendar": "UnitedStatesNYSE",
                "business_day_convention": "Following", "day_counter": "Actual365Fixed",
                "shape": "Constant", "constant_vol": 0.27}},
        }],
        "models": [{"id": "bs", "payload_type": "EquityVanillaModelSpec",
                    "payload": {"model_type": "BlackScholesAnalytic"}}],
    }
    strike = 25000.0

    def option(kind):
        return {
            "option": {
                "trade_id": kind, "underlying_id": "NDX_SYN", "quantity": 1.0,
                "settlement": "Physical",
                "payoff_type": "EquityPlainVanillaPayoff",
                "payoff": {"option_type": kind, "strike": strike},
                "exercise_type": "EquityEuropeanExercise",
                "exercise": {"expiry_date": expiry},
            },
            "discounting_curve": request["discounting_curve"],
            "volatility": "flat_vol", "model": "bs",
        }

    priced = client.price("equity_option", {"pricing": pricing,
                                            "options": [option("Call"), option("Put")]})
    call, put = (o["npv"] for o in priced["options"])
    forward_from_pricing = (call - put) / report["curve_discount_factor"] + strike
    assert abs(forward_from_pricing / report["forward"] - 1.0) < 1e-9


def test_crossed_quote_is_dropped_with_its_reason(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    q = next(x for x in request["sheet"]["quotes"]
             if x["expiry"] == "2027-03-19" and x["strike"] == 24000.0)
    q["call_bid"], q["call_ask"] = q["call_ask"], q["call_bid"]
    out = _ok(client, request)
    e = next(x for x in out["expiries"] if x["expiry"] == "2027-03-19")
    assert e["usable"]
    crossed = [d for d in e["dropped"] if d["strike"] == 24000.0]
    assert len(crossed) == 1 and crossed[0]["reason"] == "crossed quote (bid > ask)"
    truth = gen.truth(gen.SYNTHETIC_NDX_LIKE)["2027-03-19"]
    assert abs(e["forward"] / truth["forward"] - 1.0) < 1e-10


def test_expiry_with_three_pairs_is_dropped_not_rejected(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    keep = [x for x in request["sheet"]["quotes"] if x["expiry"] != "2026-12-18"]
    thin = [x for x in request["sheet"]["quotes"]
            if x["expiry"] == "2026-12-18" and x["strike"] in (23400.0, 24000.0, 24600.0)]
    request["sheet"]["quotes"] = keep + thin
    out = _ok(client, request)
    e = next(x for x in out["expiries"] if x["expiry"] == "2026-12-18")
    assert not e["usable"]
    assert "forward" not in e and "implied_dividend_yield" not in e
    assert "min_quotes_per_expiry (4)" in e["dropped_reason"]
    assert e["quotes_used"] == 0 and e["quotes_dropped"] == 1
    assert e["dropped"][0]["reason"] == e["dropped_reason"] and "strike" not in e["dropped"][0]
    assert "2026-12-18" not in [f["expiry"] for f in out["forwards"]]
    assert "2026-12-18" not in [p["point"]["date"] for p in out["dividend_curve_spec"]["points"]]
    assert len(out["forwards"]) == 7 and len(out["dividend_curve_spec"]["points"]) == 8
    # Lowering the threshold fits it from the three pairs (exact data).
    request["filter"]["min_quotes_per_expiry"] = 3
    out = _ok(client, request)
    e = next(x for x in out["expiries"] if x["expiry"] == "2026-12-18")
    assert e["usable"] and e["quotes_used"] == 3


def test_open_interest_filter(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    request["filter"]["min_open_interest"] = 3000.0
    out = _ok(client, request)
    assert out["filter"]["min_open_interest"] == 3000.0
    for e in out["expiries"]:
        assert e["usable"]
        low = [d for d in e["dropped"] if d["reason"] == "open interest below min_open_interest"]
        assert low, e["expiry"]
        for d in low:
            line = next(x for x in request["sheet"]["quotes"]
                        if x["expiry"] == e["expiry"] and x["strike"] == d["strike"])
            assert min(line["call_open_interest"], line["put_open_interest"]) < 3000.0


def test_missing_side_and_missing_strike_are_reported(client, data_dir):
    request = load_json(data_dir / EXAMPLE)
    lines = [x for x in request["sheet"]["quotes"] if x["expiry"] == "2027-09-17"]
    del lines[5]["put_bid"]
    del lines[6]["strike"]
    out = _ok(client, request)
    e = next(x for x in out["expiries"] if x["expiry"] == "2027-09-17")
    reasons = {d["reason"] for d in e["dropped"]}
    assert "missing call or put side" in reasons
    assert "strike missing or not > 0" in reasons


