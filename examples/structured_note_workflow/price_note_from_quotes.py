def step_a_load(args) -> tuple[dict, dict]:
    note_req = json.loads(Path(args.note).read_text())
    if len(note_req.get("notes", [])) != 1:
        raise SystemExit(f"{args.note}: expected exactly one note")
    note = note_req["notes"][0]
    pricing = note_req["pricing"]
    sheets = {}
    for uid, path in (("NDX", args.sheet_ndx), ("RTY", args.sheet_rty)):
        loaded = load_sheet(Path(path))
        sheet_uid = loaded["sheet"]["underlying_id"]
        if sheet_uid not in [u["underlying_id"] for u in note["underlyings"]]:
            raise SystemExit(f"{path}: sheet underlying {sheet_uid!r} is not an underlying of the note "
                             f"({[u['underlying_id'] for u in note['underlyings']]})")
        sheets[sheet_uid] = loaded
    print(f"(a) note {note['trade_id']}: as of {pricing['as_of_date']}, {note['currency']} "
          f"{note['notional']:g} notional, {len(note['events'])} events, "
          f"discounting {note['discounting_curve']} + {note['funding_spread_bp']:g} bp, "
          f"{note['performance_rule']} of {[u['underlying_id'] for u in note['underlyings']]}")
    for u in note["underlyings"]:
        spec = find(pricing["equity"]["equity_underlyings"], "id", u["underlying_id"])
        spot = find(pricing["quotes"], "id", spec["spot_quote_id"])["value"]
        line = (f"    {u['underlying_id']}: spot {spot:,.3f}, initial level {u['initial_level']:,.3f}, "
                f"dividend curve {spec['dividend_yield_curve_id']}, vol {u['volatility_id']}")
        loaded = sheets.get(u["underlying_id"])
        if loaded is None:
            line += " (no sheet: kept as in the note)"
        else:
            line += f"; sheet {loaded['sheet']['id']} ({len(loaded['sheet']['quotes'])} lines)"
            if loaded["as_of_date"] and loaded["as_of_date"] != pricing["as_of_date"]:
                line += f" WARNING sheet as-of {loaded['as_of_date']} != note as-of {pricing['as_of_date']}"
            if loaded["spot"] and abs(loaded["spot"]["value"] / spot - 1.0) > 1e-9:
                line += f" WARNING sheet spot {loaded['spot']['value']:,.3f} != note spot (the note's is used)"
        print(line)
    return note_req, sheets


def step_b_forwards(engine: Engine, note_req: dict, sheets: dict) -> dict:
    note = note_req["notes"][0]
    out = {}
    for uid, loaded in sheets.items():
        spec = find(note_req["pricing"]["equity"]["equity_underlyings"], "id", uid)
        pricing, _ = calibration_pricing(note_req, spec, note["discounting_curve"])
        body = {"pricing": pricing, "sheet": loaded["sheet"],
                "discounting_curve": note["discounting_curve"], "filter": FILTER,
                "dividend_curve_id": uid + "_DIV_IMPLIED"}
        resp = engine.post("calibrate-implied-forwards", body, f"implied_forwards_{uid}")
        usable = [e for e in resp["expiries"] if e["usable"]]
        dropped = sum(e["quotes_dropped"] for e in resp["expiries"])
        used = sum(e["quotes_used"] for e in resp["expiries"])
        print(f"(b) {uid}: {len(usable)}/{len(resp['expiries'])} expiries usable, "
              f"{used} quotes used, {dropped} dropped; dividend curve {resp['dividend_curve_spec']['id']} "
              f"({len(resp['dividend_curve_spec']['points'])} points)")
        print("      expiry        T     forward   div yield  impl DF  curve DF  funding bp  used  rmse")
        for e in resp["expiries"]:
            if not e["usable"]:
                print(f"      {e['expiry']}  {e['time']:5.3f}  dropped: {e.get('dropped_reason', '')}")
                continue
            print(f"      {e['expiry']}  {e['time']:5.3f}  {e['forward']:10.3f}  {e['implied_dividend_yield'] * 100:7.3f}%  "
                  f"{e['implied_discount_factor']:.5f}  {e['curve_discount_factor']:.5f}  "
                  f"{e['implied_funding_bp']:8.1f}  {e['quotes_used']:4d}  {e['fit_residual_rmse']:.4f}")
        out[uid] = resp
    return out


def step_c_surfaces(engine: Engine, note_req: dict, sheets: dict, forwards: dict, method: str) -> dict:
    note = note_req["notes"][0]
    out = {}
    for uid, loaded in sheets.items():
        spec = find(note_req["pricing"]["equity"]["equity_underlyings"], "id", uid)
        pricing, _ = calibration_pricing(note_req, spec, note["discounting_curve"])
        vol_id = find(note["underlyings"], "underlying_id", uid)["volatility_id"]
        body = {"pricing": pricing, "sheet": loaded["sheet"],
                "discounting_curve": note["discounting_curve"], "filter": FILTER,
                "forwards": forwards[uid]["expiries"], "method": method,
                "vol_surface_id": vol_id}
        resp = engine.post("calibrate-vol-surface", body, f"vol_surface_{uid}")
        vr = resp["vanilla_repricing"]
        grid = resp["vol_surface_spec"]["payload"]
        print(f"(c) {uid}: {resp['method']}, forwards {resp['forwards_source']}; grid "
              f"{len(resp['grid_expiries'])} expiries x {len(resp['grid_strikes'])} strikes "
              f"({grid.get('surface_interpolator')}); repricing on the grid: "
              f"{vr['inside_bid_ask']}/{vr['count']} inside bid/ask, max vol error "
              f"{vr['max_abs_vol_error'] * 100:.3f} pts"
              + ("; SVI payload returned" if "vol_surface_spec_svi" in resp else
                 f"; no SVI payload ({resp.get('vol_surface_spec_svi_note', '')})"))
        print("      expiry        used  dropped  rmse(pts)  max(pts)  butterfly        calendar")
        for e in resp["expiries"]:
            if not e["usable"]:
                print(f"      {e['expiry']}  dropped: {e.get('dropped_reason', '')}")
                continue
            bfly = "violation" if e.get("butterfly_violation") else "ok"
            if e.get("butterfly_action"):
                bfly += f" ({e['butterfly_action']})"
            cal = f"{e.get('calendar_violations', 0)} violations"
            if e.get("calendar_action"):
                cal += f" ({e['calendar_action']})"
            print(f"      {e['expiry']}  {e['quotes_used']:4d}  {e['quotes_dropped']:7d}  "
                  f"{e['rmse_vol'] * 100:9.4f}  {e['max_abs_error_vol'] * 100:8.4f}  {bfly:16s} {cal}")
        out[uid] = resp
    return out


def _strip_vol_and_dividends(note_req: dict, uids) -> dict:
    """The note with, for each listed underlying, its vol surface and its
    dividend curve removed (to be refilled)."""
    req = copy.deepcopy(note_req)
    pricing = req["pricing"]
    note = req["notes"][0]
    vol_ids = {find(note["underlyings"], "underlying_id", uid)["volatility_id"] for uid in uids}
    pricing["volatility"]["vol_surfaces"] = [
        v for v in pricing["volatility"]["vol_surfaces"] if v["id"] not in vol_ids]
    div_ids = {find(pricing["equity"]["equity_underlyings"], "id", uid)["dividend_yield_curve_id"]
               for uid in uids}
    still_used = {u["dividend_yield_curve_id"] for u in pricing["equity"]["equity_underlyings"]
                  if u["id"] not in uids} | {note["discounting_curve"]}
    pricing["rates"]["curves"] = [
        c for c in pricing["rates"]["curves"] if c["id"] not in div_ids or c["id"] in still_used]
    return req


def note_request(note_req: dict, sheets: dict, forwards: dict, vol_specs: dict,
                 paths: int, steps_per_year: int | None, repricing: bool = True) -> dict:
    """The note on the implied dividend curves and the given vol specs (one
    per underlying, under the note's own vol ids), the sheets under the
    repricing diagnostic."""
    req = _strip_vol_and_dividends(note_req, sheets.keys())
    pricing = req["pricing"]
    note = req["notes"][0]
    for uid in sheets:
        div = forwards[uid]["dividend_curve_spec"]
        pricing["rates"]["curves"].append(div)
        find(pricing["equity"]["equity_underlyings"], "id", uid)["dividend_yield_curve_id"] = div["id"]
        vol = copy.deepcopy(vol_specs[uid])
        vol["id"] = find(note["underlyings"], "underlying_id", uid)["volatility_id"]
        pricing["volatility"]["vol_surfaces"].append(vol)
    mc = note["monte_carlo"]
    mc["paths"] = paths
    mc.pop("steps_per_year", None)
    if steps_per_year is not None:
        mc["steps_per_year"] = steps_per_year
    req["diagnostics"] = {"timing": True}
    if repricing:
        req["diagnostics"].update({"vanilla_repricing": True,
                                   "vanilla_repricing_sheets": [sheets[uid]["sheet"] for uid in sheets],
                                   "vanilla_repricing_filter": FILTER})
    return req


def flat_vol_spec(as_of: str, vol: float) -> dict:
    return {"id": "", "payload_type": "BlackVolSpec",
            "payload": {"base": {"reference_date": as_of, "calendar": "UnitedStatesNYSE",
                                 "business_day_convention": "ModifiedFollowing",
                                 "day_counter": "Actual365Fixed", "shape": "Constant",
                                 "constant_vol": vol}}}


def one_year_atm_vol(as_of: str, sheet: dict, fwd_resp: dict) -> tuple[str, float, float]:
    """The Black-76 implied vol of the at-the-money quote at the sheet expiry
    closest to one year: (expiry, strike, vol). The flat-vol comparison."""
    usable = [e for e in fwd_resp["expiries"] if e["usable"]]
    target = year_fraction(as_of, as_of) + 1.0
    e = min(usable, key=lambda x: abs(x["time"] - target))
    f, df, t = e["forward"], e["implied_discount_factor"], e["time"]
    lines = [q for q in sheet["quotes"] if q["expiry"] == e["expiry"] and q.get("strike")]
    q = min(lines, key=lambda x: abs(x["strike"] - f))
    call = q["strike"] >= f
    mid = 0.5 * ((q["call_bid"] + q["call_ask"]) if call else (q["put_bid"] + q["put_ask"]))
    vol = implied_vol(mid, f, q["strike"], t, df, call)
    if vol is None:
        raise SystemExit(f"{sheet['id']}: no implied vol for the ATM quote at {e['expiry']}")
    return e["expiry"], q["strike"], vol


def summarise(note: dict) -> dict:
    """The row of the final table from one /price-structured-note result."""
    legs = note["legs"]
    first = next((p for p in note["event_probabilities"] if p.get("p_call") is not None), None)
    row = {"npv": note["npv"], "se": note["standard_error"], "status": note["status"],
           "p_call": first["p_call"] if first else None, "p_breach": note.get("p_barrier_breach"),
           "bond": legs["bond_redemption"]["pv"], "coupons": legs["coupons"]["pv"],
           "capital_loss": legs["capital_loss"]["pv"],
           "vol_shapes": [u["vol_shape"] for u in note["model"]["underlyings"]],
           "time_steps": note["model"]["time_steps"],
           "ms": note.get("timing", {}).get("total_milliseconds")}
    vr = note.get("vanilla_repricing")
    if vr:
        within = 0
        for u in vr["underlyings"]:
            for o in u["options"]:
                p = o["model_price"]
                excess = max(o["bid"] - p, p - o["ask"], 0.0)
                within += excess == 0.0 or (o["standard_error"] > 0.0 and excess <= NOISE_Z * o["standard_error"])
        row.update({"rp_inside": vr["inside_bid_ask"], "rp_within": within, "rp_count": vr["count"],
                    "rp_max_vol_err": vr.get("max_abs_vol_error"), "rp_max_se": vr["max_standard_error"],
                    "rp_note_npv": vr["note_npv"], "rp_note_se": vr["note_standard_error"]})
    return row


def print_table(rows: dict) -> None:
    print("(f)")
    print("    run    price      +/- SE   status  p_call  p_breach      bond   coupons   cap.loss"
          "  repricing inside/within noise/total  max vol err")
    for name, r in rows.items():
        p_call = f"{r['p_call']:.3f}" if r["p_call"] is not None else "   -  "
        p_br = f"{r['p_breach']:.3f}" if r["p_breach"] is not None else "   -  "
        if "rp_count" in r:
            rp = f"{r['rp_inside']:4d} / {r['rp_within']:4d} / {r['rp_count']:4d}"
            err = f"{r['rp_max_vol_err'] * 100:6.2f} pts" if r.get("rp_max_vol_err") is not None else "     -"
        else:
            rp, err = "            -         ", "     -"
        print(f"    {name:5s}  {r['npv']:8.2f}  {r['se']:7.2f}   {r['status']:7s} {p_call:6s}   {p_br:6s}  "
              f"{r['bond']:8.1f}  {r['coupons']:8.1f}  {r['capital_loss']:9.1f}  {rp:>29s}  {err}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", default="http://localhost:8080", help="JSON gateway (default %(default)s)")
    ap.add_argument("--sheet-ndx", default=str(DEFAULT_SHEETS["NDX"]),
                    help="quote-sheet JSON for the first underlying (default: the synthetic NDX sheet)")
    ap.add_argument("--sheet-rty", default=str(DEFAULT_SHEETS["RTY"]),
                    help="quote-sheet JSON for the second underlying (default: the synthetic RTY sheet)")
    ap.add_argument("--note", default=str(DEFAULT_NOTE),
                    help="price-structured-note request whose vols and dividend curves are replaced "
                         "(default: the Scotia note)")
    ap.add_argument("--paths", type=int, default=2048,
                    help="Monte Carlo paths (default %(default)s; the local-vol run and its repricing run "
                         "cost about 1 s per 1,000 paths each, against the JSON gateway's 10 s RPC deadline)")
    ap.add_argument("--no-repricing", action="store_true",
                    help="skip the vanilla_repricing diagnostic (halves the cost of each pricing)")
    ap.add_argument("--steps-per-year", type=int, default=252,
                    help="time steps per year of the local-vol simulation (default %(default)s)")
    ap.add_argument("--method", choices=["SviPerExpiry", "AndreasenHuge"], default="SviPerExpiry",
                    help="surface fit (default %(default)s; AndreasenHuge returns the grid only)")
    ap.add_argument("--flat", action="store_true",
                    help="also price with flat vols = the one-year ATM implied vol of each sheet "
                         "(the level-1 comparison line)")
    ap.add_argument("--out-dir", default=None,
                    help="where the request and response bodies are written (default: a temp dir)")
    args = ap.parse_args()

    out_dir = Path(args.out_dir) if args.out_dir else Path(tempfile.mkdtemp(prefix="quantra_note_"))
    out_dir.mkdir(parents=True, exist_ok=True)
    engine = Engine(args.url, out_dir)
    try:
        note_req, sheets = step_a_load(args)
        as_of = note_req["pricing"]["as_of_date"]
        forwards = step_b_forwards(engine, note_req, sheets)
        surfaces = step_c_surfaces(engine, note_req, sheets, forwards, args.method)

        runs = {"grid": {uid: s["vol_surface_spec"] for uid, s in surfaces.items()}}
        if all("vol_surface_spec_svi" in s for s in surfaces.values()):
            runs["svi"] = {uid: s["vol_surface_spec_svi"] for uid, s in surfaces.items()}
        rows = {}
        for name, specs in runs.items():
            body = note_request(note_req, sheets, forwards, specs, args.paths, args.steps_per_year,
                                repricing=not args.no_repricing)
            resp = engine.post("price-structured-note", body, f"price_note_{name}")
            note = resp["notes"][0]
            rows[name] = r = summarise(note)
            print(f"(d) {name}: {' / '.join(r['vol_shapes'])}, {r['time_steps']} time steps, {args.paths} paths: "
                  f"{r['npv']:.2f} +/- {r['se']:.2f} per {note_req['notes'][0]['notional']:g}"
                  + (f"; repriced on its own paths {r['rp_note_npv']:.2f} +/- {r['rp_note_se']:.2f}; "
                     f"{r['rp_count']} quotes, max SE {r['rp_max_se']:.3f}" if "rp_count" in r else "")
                  + f"; engine {r['ms'] / 1000:.1f} s")
        if args.flat:
            specs = {}
            for uid, loaded in sheets.items():
                expiry, strike, vol = one_year_atm_vol(as_of, loaded["sheet"], forwards[uid])
                print(f"(e) {uid}: flat vol {vol * 100:.2f}% = the {expiry} ATM quote (strike {strike:,.2f})")
                specs[uid] = flat_vol_spec(as_of, vol)
            body = note_request(note_req, sheets, forwards, specs, args.paths, None,
                                repricing=not args.no_repricing)
            note = engine.post("price-structured-note", body, "price_note_flat")["notes"][0]
            rows["flat"] = r = summarise(note)
            print(f"(e) flat: {' / '.join(r['vol_shapes'])}, {r['time_steps']} time steps: "
                  f"{r['npv']:.2f} +/- {r['se']:.2f}; engine {r['ms'] / 1000:.1f} s")
        print_table(rows)
        print(f"request and response bodies: {out_dir}")
    except EngineError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    return 0


