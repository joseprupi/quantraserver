#!/usr/bin/env python3
"""Price a structured note from listed option quotes (level 2 of
examples/structured_note_workflow/README.md).

Three calls per underlying, then one per surface payload:

  1. POST /calibrate-implied-forwards   quote sheet -> forwards, implied
                                        dividend yields, a dividend curve spec
  2. POST /calibrate-vol-surface        quote sheet + forwards -> the Black
                                        surface as a strike x expiry grid
                                        (vol_surface_spec) and, with the SVI
                                        method, as SVI slices
                                        (vol_surface_spec_svi)
  3. POST /price-structured-note        the note with the implied dividend
                                        curves and the surfaces pasted in,
                                        `diagnostics.vanilla_repricing` with
                                        the sheets as the acceptance check

By default it runs on the Bank of Nova Scotia autocallable
(examples/data/structured_note/scotia_..._us06419jme72.json, NDX / RTY
worst-of) and the two SYNTHETIC quote sheets under examples/data/vol_surface/
(generated by tests/tools/make_synthetic_quote_sheet.py on the note's own
market; nothing in them is market data, so the prices are not valuations of
the note). Point --sheet-ndx / --sheet-rty at sheets of your own, for
instance the output of tools/option_quotes/cboe_eod_to_quote_sheet.py, and
--note at any note whose underlyings the sheets cover.

Python 3 standard library plus `requests`. Every request body it sends and
every response it gets back are written to --out-dir so they can be
inspected or replayed with curl (price_note_from_quotes.sh does that).
"""

from __future__ import annotations

import argparse
import copy
import json
import math
import sys
import tempfile
from datetime import date, timedelta
from pathlib import Path

import requests

REPO = Path(__file__).resolve().parents[2]
DEFAULT_NOTE = REPO / "examples" / "data" / "structured_note" / \
    "scotia_autocallable_trigger_ndx_rty_us06419jme72.json"
DEFAULT_SHEETS = {
    "NDX": REPO / "examples" / "data" / "vol_surface" / "synthetic_scotia_ndx_sheet.json",
    "RTY": REPO / "examples" / "data" / "vol_surface" / "synthetic_scotia_rty_sheet.json",
}
# The filter of both calibrations and of the repricing diagnostic: the
# engine's defaults, written out so that the request files show them.
FILTER = {"max_relative_spread": 0.05, "min_quotes_per_expiry": 4, "moneyness_window": 0.25}
# An option is "within noise" when its model price is no further than this
# many standard errors outside its bid/ask band (the gate's criterion).
NOISE_Z = 3.5


# ---------------------------------------------------------------------------
# HTTP
# ---------------------------------------------------------------------------
class EngineError(Exception):
    pass


class Engine:
    def __init__(self, url: str, out_dir: Path):
        self.url = url.rstrip("/")
        self.out_dir = out_dir
        self.session = requests.Session()

    def post(self, endpoint: str, body: dict, name: str) -> dict:
        """POST `body` to /<endpoint>; the request and the response are
        written to out_dir as <name>_request.json / <name>_response.json."""
        (self.out_dir / f"{name}_request.json").write_text(json.dumps(body, indent=2) + "\n")
        try:
            r = self.session.post(f"{self.url}/{endpoint}", json=body, timeout=600)
        except requests.RequestException as exc:
            raise EngineError(f"POST {self.url}/{endpoint}: {exc}") from exc
        (self.out_dir / f"{name}_response.json").write_text(r.text + "\n")
        if r.status_code != 200:
            raise EngineError(f"POST /{endpoint} -> HTTP {r.status_code}\n{r.text.strip()}")
        return r.json()


# ---------------------------------------------------------------------------
# Black-76 helpers (for the --flat comparison line only)
# ---------------------------------------------------------------------------
def _norm_cdf(x: float) -> float:
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def _black(forward: float, strike: float, vol: float, t: float, df: float, call: bool) -> float:
    if vol <= 0.0 or t <= 0.0:
        return df * max((forward - strike) if call else (strike - forward), 0.0)
    s = vol * math.sqrt(t)
    d1 = (math.log(forward / strike) + 0.5 * s * s) / s
    d2 = d1 - s
    if call:
        return df * (forward * _norm_cdf(d1) - strike * _norm_cdf(d2))
    return df * (strike * _norm_cdf(-d2) - forward * _norm_cdf(-d1))


def implied_vol(price: float, forward: float, strike: float, t: float, df: float, call: bool) -> float | None:
    """Black-76 implied vol of `price` by bisection; None when it does not solve."""
    lo, hi = 1e-4, 5.0
    if not (_black(forward, strike, lo, t, df, call) <= price <= _black(forward, strike, hi, t, df, call)):
        return None
    for _ in range(100):
        mid = 0.5 * (lo + hi)
        if _black(forward, strike, mid, t, df, call) < price:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def year_fraction(as_of: str, expiry: str) -> float:
    return (date.fromisoformat(expiry) - date.fromisoformat(as_of)).days / 365.0


