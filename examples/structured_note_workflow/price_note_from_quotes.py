def load_sheet(path: Path) -> dict:
    """A quote-sheet file: either the bare `OptionQuoteSheet` or the wrapper
    the Cboe converter writes ({as_of_date, spot, sheet, source}); the wrapper's
    `spot` is checked against the note's."""
    data = json.loads(path.read_text())
    sheet = data["sheet"] if "sheet" in data else data
    for key in ("id", "underlying_id", "quotes"):
        if key not in sheet:
            raise SystemExit(f"{path}: not a quote sheet (no '{key}')")
    return {"sheet": sheet, "spot": data.get("spot"), "as_of_date": data.get("as_of_date")}


def find(items: list, key: str, value):
    for item in items:
        if item.get(key) == value:
            return item
    raise SystemExit(f"no entry with {key} = {value!r}")


def flat_zero_curve(curve_id: str, as_of: str, last: str, rate: float) -> dict:
    def point(d):
        return {"point_type": "ZeroRatePoint",
                "point": {"date": d, "zero_rate": rate, "compounding": "Continuous",
                          "frequency": "Annual"}}
    return {"id": curve_id, "day_counter": "Actual365Fixed", "interpolator": "Linear",
            "reference_date": as_of, "bootstrap_trait": "InterpolatedZero",
            "points": [point(as_of), point(last)]}


def calibration_pricing(note_req: dict, underlying: dict, discounting_curve: str) -> tuple[dict, str]:
    """The `pricing` block of the two calibration calls: the as-of date, the
    underlying's spot quote and the note's discounting curve, with a flat 0 %
    placeholder dividend curve (the fit does not read it)."""
    pricing = note_req["pricing"]
    as_of = pricing["as_of_date"]
    spot = find(pricing["quotes"], "id", underlying["spot_quote_id"])
    curve = find(pricing["rates"]["curves"], "id", discounting_curve)
    placeholder = underlying["id"] + "_DIV_PLACEHOLDER"
    und = {k: v for k, v in underlying.items() if k != "dividend_yield_curve_id"}
    und["dividend_yield_curve_id"] = placeholder
    last = (date.fromisoformat(as_of) + timedelta(days=3653)).isoformat()
    return {
        "as_of_date": as_of,
        "quotes": [spot],
        "rates": {"curves": [curve, flat_zero_curve(placeholder, as_of, last, 0.0)]},
        "equity": {"equity_underlyings": [und]},
    }, placeholder


